def source_of(name: str) -> tuple[str, str, str]:
    for prefix, gen, res, scr in SOURCES:
        if name.startswith(prefix):
            return gen, res, scr
    return "?", "?", "?"


def main() -> None:
    macros: dict[str, str] = {}
    for f in ("macros.tex", "real_macros.tex"):
        text = (GEN / f).read_text()
        for m in re.finditer(r"\\(?:re)?newcommand\{\\(\w+)\}\{(.*)\}\s*$", text, re.M):
            macros[m.group(1)] = m.group(2)
    texts = {s.name: s.read_text() for s in SECTIONS}
    rows = []
    for name, value in sorted(macros.items()):
        if name.startswith("REAL"):
            continue
        used = [s for s, t in texts.items() if re.search(rf"\\{name}(?![A-Za-z])", t)]
        gen, res, scr = source_of(name)
        short = value if len(value) < 40 else value[:37] + "..."
        rows.append(
            f"| `{name}` | {short.replace('|', '/')} | {', '.join(used) or '(unused)'} | {gen} | {res} | {scr} |"
        )
    head = (
        "# Traceability: quantitative claim -> script -> result\n\n"
        "Generated by `scripts/make_traceability.py` from `latex/generated/*.tex`. Every number in the paper is a\n"
        "macro produced by `scripts/make_paper_assets.py` (via `extra_assets.py` and `make_real_assets.py`) from the\n"
        "JSON files in `results/`; the last column is the script that produced that JSON. Prose constants such as\n"
        "the nominal levels (5%, 95%) and design parameters are in the text and are listed in `docs/experiments.md`.\n\n"
        "| Macro | Value | Used in | Asset script | Result file | Experiment script |\n|---|---|---|---|---|---|\n"
    )
    (ROOT / "TRACEABILITY.md").write_text(head + "\n".join(rows) + "\n", encoding="utf-8")
    print(len(rows), "macros traced")


if __name__ == "__main__":
    main()
